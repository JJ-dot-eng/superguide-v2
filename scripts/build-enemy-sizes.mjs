// Offline projection of wiki size categories onto the combat roster.
// Usage: node scripts/build-enemy-sizes.mjs [--stdout]
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { enemies } from '../dist/data/combat-data.js';

const root = new URL('../', import.meta.url);
const categories = { small: 'Small Enemies', medium: 'Medium Enemies', large: 'Large Enemies', massive: 'Massive Enemies' };

export function buildEnemySizes(snapshot, roster) {
  const byTitle = new Map();
  for (const [size, expectedName] of Object.entries(categories)) {
    const category = snapshot.categories?.[size];
    if (category?.category !== expectedName || !Array.isArray(category.members)) throw new Error(`Missing or unexpected size category: ${size}`);
    for (const page of category.members) {
      if (typeof page.title !== 'string' || !page.title) throw new Error(`Invalid page title in ${size}`);
      if (byTitle.has(page.title)) throw new Error(`Duplicate or ambiguous size category: ${page.title}`);
      byTitle.set(page.title, { ...page, size, category: expectedName });
    }
  }
  const enemySizes = {}, enemySizeEvidence = {}, unmappedEnemySizes = {};
  // Stable ID order; source category/page ordering does not affect output.
  for (const enemy of [...roster].sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0)) {
    if (Object.hasOwn(enemySizes, enemy.id)) throw new Error(`Duplicate enemy ID: ${enemy.id}`);
    const url = new URL(enemy.source);
    if (url.hostname !== 'helldivers.wiki.gg' || !url.pathname.startsWith('/wiki/')) throw new Error(`Unexpected enemy source: ${enemy.id}`);
    const title = decodeURIComponent(url.pathname.slice('/wiki/'.length)).replaceAll('_', ' ');
    const match = byTitle.get(title);
    enemySizes[enemy.id] = match?.size ?? null;
    enemySizeEvidence[enemy.id] = {
      title, source: enemy.source, category: match?.category ?? null,
      pageid: match?.pageid ?? null, revision: match?.revision ?? null,
    };
    if (!match) unmappedEnemySizes[enemy.id] = '수집한 소형·중형·대형·초대형 분류에 이 적의 페이지가 없어 크기를 확인하지 못했습니다.';
  }
  return { enemySizes, enemySizeEvidence, unmappedEnemySizes };
}

const snapshot = JSON.parse(await readFile(new URL('db/source/wiki_enemy_sizes.json', root), 'utf8'));
const result = buildEnemySizes(snapshot, enemies);
const exports = {
  enemySizesCheckedAt: snapshot.retrievedAt,
  enemySizesSource: { source: snapshot.source, file: 'db/source/wiki_enemy_sizes.json', categories },
  ...result,
};
const output = '// Generated by scripts/build-enemy-sizes.mjs from local db/source/wiki_enemy_sizes.json. Do not edit by hand.\n'
  + Object.entries(exports).map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};\n`).join('\n');

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--stdout')) process.stdout.write(output);
  else {
    await writeFile(new URL('dist/data/enemy-sizes.js', root), output, 'utf8');
    const missing = Object.keys(result.unmappedEnemySizes).length;
    console.log(`Generated dist/data/enemy-sizes.js: ${enemies.length - missing} mapped / ${missing} explicitly unmapped (${enemies.length} combat entries).`);
  }
}
